#!/usr/bin/env python3
"""Generate the verified pitch subset used by Japanese curriculum lessons."""

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).with_name('accents.tsv')
OUTPUT = ROOT / 'app/lib/services/generated_pitch_accent.dart'


def collect_targets():
    pairs = set()
    rust = (ROOT / 'server/src/data.rs').read_text(encoding='utf-8')
    rust_pattern = re.compile(
        r'target_text:\s*"([^"\\]*(?:\\.[^"\\]*)*)"'
        r'.{0,240}?phonetic_or_kana:\s*"([^"\\]*(?:\\.[^"\\]*)*)"',
        re.DOTALL,
    )
    pairs.update(rust_pattern.findall(rust))

    workplace = json.loads(
        (ROOT / 'curriculum/workplace_expansion.json').read_text(encoding='utf-8')
    )
    pairs.update(
        (lesson['target_text'], lesson['phonetic_or_kana']) for lesson in workplace
    )
    return pairs


def select_entries(lines, targets):
    selected = set()
    for line in lines:
        fields = line.rstrip('\r\n').split('\t')
        if len(fields) != 3 or (fields[0], fields[1]) not in targets:
            continue
        try:
            downsteps = [int(value) for value in fields[2].split(',')]
        except ValueError:
            continue
        selected.update((fields[0], fields[1], downstep) for downstep in downsteps)
    return sorted(selected)


def render_dart(entries):
    lines = [
        '// Generated by tools/kanjium/generate_pitch_accent.py; do not edit.',
        'const List<Map<String, Object>> generatedPitchAccentEntries = [',
    ]
    for word, reading, downstep in entries:
        fields = json.dumps(
            {'word': word, 'reading': reading, 'downstep': downstep},
            ensure_ascii=False,
            separators=(',', ': '),
        )
        lines.append(f'  {fields},')
    lines.append('];')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()

    targets = collect_targets()
    entries = select_entries(SOURCE.read_text(encoding='utf-8').splitlines(), targets)
    generated = render_dart(entries)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != generated:
            raise SystemExit('Generated pitch-accent Dart is stale; rerun this script.')
    else:
        OUTPUT.write_text(generated, encoding='utf-8')
    print(
        f'{len(entries)} pitch patterns for '
        f'{len({(word, reading) for word, reading, _ in entries})} '
        f'exact word-reading pairs; {len(targets)} curriculum pairs checked.'
    )


if __name__ == '__main__':
    main()
